#!/usr/bin/env python3
"""Trace the Proximata mark into SVG polygons for large-scale use.

The brand book embeds the mark only as a raster mask (see
build-brand-assets.py). At the sizes the side supergraphic uses (well over
1000px tall) the PNG turns soft, so this traces each of the mark's pieces into
a straight-edged polygon and writes them as a TypeScript module.

Usage: python3 scripts/build-mark-paths.py
Output: src/components/sites/proximata/mark-paths.ts
Requires Pillow, NumPy and scikit-image.
"""

import pathlib

import numpy as np
from PIL import Image
from skimage import measure

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "public/sites/proximata/images/brand/proximata-mark.png"
TARGET = ROOT / "src/components/sites/proximata/mark-paths.ts"

# Max deviation (px at the 1016x1024 source size) when simplifying outlines.
TOLERANCE = 1.2


def main() -> None:
    alpha = np.array(Image.open(SOURCE).convert("RGBA"))[:, :, 3] > 127
    height, width = alpha.shape
    labels = measure.label(alpha, connectivity=2)

    paths = []
    for region in sorted(measure.regionprops(labels), key=lambda r: r.bbox):
        piece = np.pad(labels == region.label, 1).astype(float)
        contour = max(measure.find_contours(piece, 0.5), key=len)
        polygon = measure.approximate_polygon(contour, tolerance=TOLERANCE)[:-1]
        # find_contours returns (row, col) in padded coordinates.
        points = [f"{col - 1:.1f} {row - 1:.1f}" for row, col in polygon]
        paths.append("M" + "L".join(points) + "Z")

    lines = [
        "// Generated by scripts/build-mark-paths.py from the Proximata mark; do not edit.",
        "",
        f'export const MARK_VIEWBOX = "0 0 {width} {height}";',
        "",
        "/** One straight-edged polygon per piece of the mark. */",
        "export const MARK_PATHS = [",
        *[f'  "{path}",' for path in paths],
        "] as const;",
        "",
    ]
    TARGET.write_text("\n".join(lines))
    print(f"wrote {TARGET.relative_to(ROOT)}: {len(paths)} pieces, viewBox 0 0 {width} {height}")


if __name__ == "__main__":
    main()
